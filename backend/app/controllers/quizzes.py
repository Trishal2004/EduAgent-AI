@router.post("/quizzes/{quiz_id}/submit")
async def submit_quiz(
    quiz_id: UUID,
    request: QuizSubmitRequest,
    db: Session = Depends(deps.get_db),
    current_user: User = Depends(deps.get_current_user)
):
    """
    Submits user answers for a quiz. 
    The backend automatically grades it against the stored correct answers.
    Returns the final score, the correct answers, and explanations.
    """
    repo = QuizRepository(db)
    quiz = repo.get_quiz_by_id(quiz_id, current_user.id) # type: ignore
    if not quiz:
        raise HTTPException(status_code=404, detail="Quiz not found")

    correct_count = 0
    unanswered_count = 0
    total_questions = len(quiz.questions) # type: ignore
    graded_results = []

    # Map user answers against true answers
    user_answers_str_keys = {str(k): v for k, v in request.answers.items()}
    
    ai_questions_to_grade = []
    graded_results_map = {}

    for question in quiz.questions:
        q_id = str(question.id)
        user_answer = user_answers_str_keys.get(q_id, "")
        is_unanswered = not user_answer or user_answer.strip() == ""
        
        if not is_unanswered:
            if question.question_type in ["mcq", "true_false"]:
                is_correct = user_answer.strip().lower() == question.correct_answer.strip().lower()
                graded_results_map[q_id] = is_correct
            else:
                ai_questions_to_grade.append({
                    "question_id": q_id,
                    "question_text": question.question_text,
                    "correct_answer": question.correct_answer,
                    "user_answer": user_answer
                })
        else:
            graded_results_map[q_id] = False
            unanswered_count += 1
            
    if ai_questions_to_grade:
        from app.services.gemini_service import GeminiService
        from app.DTOs.quiz import AIGradingResponse
        try:
            gemini = GeminiService()
            system_prompt = "You are an AI teacher grading a quiz. For each question, compare the user's answer to the correct answer. Determine if the user's answer is conceptually correct. It does not need to be an exact verbatim match, but it must demonstrate understanding of the core concept. Output a boolean 'is_correct' for each question_id."
            user_prompt = f"Grade the following answers:\n{ai_questions_to_grade}"
            
            ai_response = gemini.generate_json(system_prompt, user_prompt, AIGradingResponse)
            
            for res in ai_response.get("results", []):
                graded_results_map[res["question_id"]] = res["is_correct"]
        except Exception as e:
            print("AI Grading Failed:", e)
            # Fallback to strict string match if API fails
            for q in ai_questions_to_grade:
                is_correct = q["user_answer"].strip().lower() == q["correct_answer"].strip().lower()
                graded_results_map[q["question_id"]] = is_correct

    for question in quiz.questions:
        q_id = str(question.id)
        user_answer = user_answers_str_keys.get(q_id, "")
        is_unanswered = not user_answer or user_answer.strip() == ""
        is_correct = graded_results_map.get(q_id, False)
        
        if is_correct:
            correct_count += 1
            
        graded_results.append({
            "question_id": q_id,
            "question_text": question.question_text,
            "user_answer": user_answer if not is_unanswered else "Unanswered",
            "correct_answer": question.correct_answer,
            "explanation": question.explanation,
            "is_correct": is_correct,
            "is_unanswered": is_unanswered
        })

    incorrect_count = total_questions - correct_count - unanswered_count
    score_percentage = (correct_count / total_questions) * 100 if total_questions > 0 else 0.0

    # Save the attempt
    repo.create_attempt(
        quiz_id=quiz.id, # type: ignore
        owner_id=current_user.id, # type: ignore
        score=score_percentage,
        total_questions=total_questions,
        user_answers={"results": graded_results, "raw": user_answers_str_keys},
        time_spent_seconds=request.time_spent_seconds
    )
    
    # Mark as completed
    repo.update_quiz_status(quiz.id, current_user.id, "Completed") # type: ignore

    return {
        "score": score_percentage,
        "correct_count": correct_count,
        "incorrect_count": incorrect_count,
        "unanswered_count": unanswered_count,
        "total_questions": total_questions,
        "results": graded_results
    }

@router.get("/quizzes/{quiz_id}/results")
async def get_quiz_results(
    quiz_id: UUID,
    db: Session = Depends(deps.get_db),
    current_user: User = Depends(deps.get_current_user)
):
    """Retrieves the full graded results of the most recent attempt for a completed quiz."""
    repo = QuizRepository(db)
    quiz = repo.get_quiz_by_id(quiz_id, current_user.id) # type: ignore
    if not quiz or quiz.status != "Completed":
        raise HTTPException(status_code=404, detail="Quiz not found or not completed")
    
    if not quiz.attempts:
        raise HTTPException(status_code=404, detail="No attempts found for this quiz")
        
    latest_attempt = quiz.attempts[-1]
    user_answers_data = latest_attempt.user_answers
    
    if isinstance(user_answers_data, dict) and "results" in user_answers_data:
        graded_results = user_answers_data["results"]
    else:
        # Fallback for old attempts that only stored raw dict
        graded_results = []
        raw_answers = user_answers_data if isinstance(user_answers_data, dict) else {}
        for question in quiz.questions:
            q_id = str(question.id)
            user_ans = raw_answers.get(q_id, "")
            is_unanswered = not user_ans or user_ans.strip() == ""
            # Best effort grading for old text answers (exact match)
            is_correct = user_ans.strip().lower() == question.correct_answer.strip().lower() if not is_unanswered else False
            graded_results.append({
                "question_id": q_id,
                "question_text": question.question_text,
                "user_answer": user_ans if not is_unanswered else "Unanswered",
                "correct_answer": question.correct_answer,
                "explanation": question.explanation,
                "is_correct": is_correct,
                "is_unanswered": is_unanswered
            })
            
    correct_count = sum(1 for r in graded_results if r.get("is_correct"))
    unanswered_count = sum(1 for r in graded_results if r.get("is_unanswered"))
    incorrect_count = len(graded_results) - correct_count - unanswered_count
            
    return {
        "score": latest_attempt.score,
        "correct_count": correct_count,
        "incorrect_count": incorrect_count,
        "unanswered_count": unanswered_count,
        "total_questions": latest_attempt.total_questions,
        "results": graded_results
    }

